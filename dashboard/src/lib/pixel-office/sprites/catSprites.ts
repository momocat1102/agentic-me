export interface CatSpriteSet extends CharacterSprites {
  /** 2 sit frames, facing down */
  sit: [SpriteData, SpriteData]
  /** 1 sleep frame, static curled pose */
  sleep: SpriteData
}

/** Build a CatSpriteSet for a given variant.
 *  variant 0 = orange cat (default), variant 1 = gray cat.
 *
 *  Walk uses 4 frames (stand/walk alternating).
 *  Typing and reading reuse sit sprites (a sitting cat is "typing").
 */
export function getCatSprites(variant = 0): CatSpriteSet {
  const walk = (s1: SpriteData, s2: SpriteData): [SpriteData, SpriteData, SpriteData, SpriteData] =>
    [s1, s2, s1, s2]
  const idle = (s: SpriteData): [SpriteData, SpriteData] => [s, s]

  const isGray = variant === 1

  const sitF1 = isGray ? GRAY_CAT_SIT_1 : CAT_SIT_1
  const sitF2 = isGray ? GRAY_CAT_SIT_2 : CAT_SIT_2

  const d1  = isGray ? GRAY_CAT_DOWN_1  : CAT_DOWN_1
  const d2  = isGray ? GRAY_CAT_DOWN_2  : CAT_DOWN_2
  const l1  = isGray ? GRAY_CAT_LEFT_1  : CAT_LEFT_1
  const l2  = isGray ? GRAY_CAT_LEFT_2  : CAT_LEFT_2
  const r1  = isGray ? GRAY_CAT_RIGHT_1 : CAT_RIGHT_1
  const r2  = isGray ? GRAY_CAT_RIGHT_2 : CAT_RIGHT_2
  const u1  = isGray ? GRAY_CAT_UP_1    : CAT_UP_1
  const u2  = isGray ? GRAY_CAT_UP_2    : CAT_UP_2
  const slp = isGray ? GRAY_CAT_SLEEP   : CAT_SLEEP

  return {
    walk: {
      [0]: walk(d1, d2),
      [1]: walk(l1, l2),
      [2]: walk(r1, r2),
      [3]: walk(u1, u2),
    },
    typing: {
      [0]: idle(sitF1),
      [1]: idle(sitF1),
      [2]: idle(sitF1),
      [3]: idle(sitF1),
    },
    reading: {
      [0]: idle(sitF2),
      [1]: idle(sitF2),
      [2]: idle(sitF2),
      [3]: idle(sitF2),
    },
    sit: [sitF1, sitF2],
    sleep: slp,
  }
}
